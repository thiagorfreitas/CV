function detectLang() {
  const list = (navigator.languages || [navigator.language] || []);
  for (const raw of list) {
    const code = String(raw || "").slice(0, 2).toLowerCase();
    if (code === "pt" || code === "en" || code === "es") return code;
  }
  return "en";
}

let lang = detectLang();
let theme = "light";

function pick(v, l) {
  return v && typeof v === "object" && !Array.isArray(v) ? v[l] : v;
}

