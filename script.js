function setI18nText() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const path = el.getAttribute("data-i18n").split(".");
    let val = D;
    for (const key of path) val = val[key];
    el.textContent = val[lang];
  });
}

function setPdfLink() {
  const btn = document.getElementById("pdf-btn");
  const url = PDF_URL[lang];
  btn.href = url;
  btn.setAttribute("download", url);
}

function setLangButtons() {
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function setThemeButton() {
  const btn = document.getElementById("theme-toggle");
  btn.textContent = theme === "light" ? D.themeDark[lang] : D.themeLight[lang];
}

function render() {
  setI18nText();
  renderExp();
  renderSkills();
  renderLangs();
  renderCerts();
  setPdfLink();
  setLangButtons();
  setThemeButton();
}

function switchLang(next) {
  if (next === lang) return;
  const main = document.querySelector("main");
  if (reduceMotion) {
    lang = next;
    render();
    setupReveal();
    return;
  }
  main.classList.add("i18n-fade", "i18n-out");
  window.setTimeout(() => {
    lang = next;
    render();
    setupReveal();
    main.classList.remove("i18n-out");
  }, 180);
}

function applyTheme() {
  document.documentElement.setAttribute("data-theme", theme);
  setThemeButton();
}

let revealObserver = null;
let revealHasRun = false;
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

function setupReveal() {
  const targets = document.querySelectorAll(".reveal:not(.visible)");
  if (reduceMotion || !("IntersectionObserver" in window)) {
    targets.forEach(el => el.classList.add("visible"));
    return;
  }
  if (revealHasRun) {
    // Content was just swapped by a language change, not a fresh scroll — show as-is.
    targets.forEach(el => el.classList.add("visible"));
    return;
  }
  if (!revealObserver) {
    revealObserver = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0, rootMargin: "0px 0px -10% 0px" });
  }
  targets.forEach(el => revealObserver.observe(el));
  revealHasRun = true;
}

document.addEventListener("DOMContentLoaded", function () {
  const savedTheme = localStorage.getItem("theme");
  if (savedTheme === "dark" || savedTheme === "light") theme = savedTheme;
  applyTheme();
  render();
  setupReveal();

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => switchLang(btn.dataset.lang));
  });

  document.getElementById("theme-toggle").addEventListener("click", function () {
    theme = theme === "light" ? "dark" : "light";
    localStorage.setItem("theme", theme);
    applyTheme();
  });

  // Header shadow + hero parallax on scroll
  const header = document.querySelector(".site-header");
  const hero = document.querySelector(".hero");

  function onScroll() {
    const scrolled = window.pageYOffset;
    header.classList.toggle("scrolled", scrolled > 4);
    if (!reduceMotion && hero) {
      const shift = Math.min(scrolled * 0.25, 60);
      hero.style.transform = `translateY(${shift * -0.3}px)`;
      hero.style.opacity = String(Math.max(1 - scrolled / 600, 0.4));
    }
  }

  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
});
